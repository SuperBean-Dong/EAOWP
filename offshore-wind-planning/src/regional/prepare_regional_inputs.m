function prepared = prepare_regional_inputs(publicCfg)
%PREPARE_REGIONAL_INPUTS Build private P44 inputs from this repository's B0.
% Reads one generated B0 checkpoint at a time, never the full results array.
% No original research inputs, precomputed results or archived CSVs are used.
sourceDir=fileparts(mfilename('fullpath'));
assert(isfile(publicCfg.baselineFile),'p44:MissingBaseline', ...
    'Run run_stage34 first; missing B0 file: %s',publicCfg.baselineFile);
assert(isfile(publicCfg.priceFile),'p44:MissingPrice','Missing price input.');
assert(isfile(publicCfg.compactWindFile),'p44:MissingWind', ...
    'Run run_stage1 first; missing its compact wind file: %s',publicCfg.compactWindFile);
header=load(publicCfg.baselineFile,'baseline_meta','price_CNY_per_MWh');
assert(all(isfield(header,{'baseline_meta','price_CNY_per_MWh'})), ...
    'p44:BaselineSchema','B0 must contain baseline_meta and price_CNY_per_MWh.');
meta=header.baseline_meta;
assert(isfield(meta,'all_complete') && logical(meta.all_complete), ...
    'p44:IncompleteBaseline','All B0 grids/candidate searches must be complete.');
assert(isfield(meta,'source_price_sha256') && ...
    strcmpi(meta.source_price_sha256,p44_sha256(publicCfg.priceFile,true)), ...
    'p44:ChangedPrice','The supplied price file differs from the B0 source.');
price_CNY_per_MWh=double(header.price_CNY_per_MWh(:));
assert(numel(price_CNY_per_MWh)==8760 && all(isfinite(price_CNY_per_MWh)) ...
    && all(price_CNY_per_MWh>0),'p44:PriceSchema',['P44 retains its original strictly positive-price scope (8760 hours). ', ...
    'B0 may accept finite nonpositive prices; this regional model does not.']);
assert(isfield(meta,'model_signature'),'p44:BaselineSignature','Missing B0 signature.');
baselineSHA=p44_sha256(publicCfg.baselineFile,true);
sourceCheckpoints=fullfile(fileparts(publicCfg.baselineFile),'checkpoints');
files=dir(fullfile(sourceCheckpoints,'grid_*.mat'));
assert(~isempty(files),'p44:MissingCheckpoints', ...
    'B0 per-grid record/checkpoint files are required: %s',sourceCheckpoints);
inputRoot=fullfile(publicCfg.regionalOutputDir,'input_cache');
dataDir=fullfile(inputRoot,'data'); snapshotDir=fullfile(inputRoot,'baseline_snapshot');
checkpointDir=fullfile(snapshotDir,'stage4_checkpoints');
for folder={dataDir,snapshotDir,checkpointDir}
    if ~isfolder(folder{1}), mkdir(folder{1}); end
end
manifestFile=fullfile(dataDir,'input_manifest.json');
inputFile=fullfile(dataDir,'p44_inputs.mat'); priceFile=fullfile(dataDir,'p44_price.mat');
windStat=dir(publicCfg.compactWindFile);
fingerprint=p44_sha256(jsonencode(struct('baseline',baselineSHA, ...
    'price',meta.source_price_sha256,'wind_file',publicCfg.compactWindFile, ...
    'wind_bytes',windStat.bytes,'wind_datenum',windStat.datenum, ...
    'adapter',p44_sha256([mfilename('fullpath') '.m'],true), ...
    'pairs',p44_sha256(fullfile(sourceDir,'p44_cross_grid_pairs.m'),true))));
prepared=struct('BaselineDir',snapshotDir,'InputFile',inputFile, ...
    'PriceFile',priceFile,'ManifestFile',manifestFile, ...
    'SourceCodeDir',sourceDir,'WindFile',publicCfg.compactWindFile);
if isfile(manifestFile) && isfile(inputFile) && isfile(priceFile)
    old=jsondecode(fileread(manifestFile));
    if isfield(old,'preparation_fingerprint') && strcmp(old.preparation_fingerprint,fingerprint)
        assert(strcmp(p44_sha256(inputFile,true),old.input_file_sha256), ...
            'p44:PreparedInputChanged','Prepared regional inputs changed.');
        assert(numel(dir(fullfile(checkpointDir,'grid_*.mat')))==old.candidates, ...
            'p44:PreparedSnapshots','Prepared snapshot count changed. Use a fresh regionalOutputDir.');
        return;
    end
end
assert(~isfile(inputFile),'p44:ChangedRegionalInputs', ...
    'Source inputs changed. Use a fresh regionalOutputDir to preserve prior runs.');
records=cell(0,1); ids=zeros(0,1); seen=zeros(0,1); summaryRows=zeros(0,4);
fields={'grid_index','status','wind_farm_capacity','turbine_count','turbine_xy_m', ...
    'NPV_best','platform_turbine_cost','platform_detail','internal_cable_cost', ...
    'collection_edge_detail','beta','optimal_platform','optimal_epsilon','E_bat_best', ...
    'export_mode','storage_case','export_system_cost_CNY','battery_cost_CNY', ...
    'total_cost_best','LCOE_min','AEP_raw_MWh','AEP_wake_adjusted_MWh', ...
    'wake_loss_fraction','availability_factor','actual_wind_peak_MW', ...
    'discounted_onshore_energy_kWh','distance_to_shore_km'};
for k=1:numel(files)
    entry=load(fullfile(files(k).folder,files(k).name),'record','checkpoint');
    assert(all(isfield(entry,{'record','checkpoint'})),'p44:CheckpointSchema', ...
        'Each B0 checkpoint must contain record and checkpoint.');
    r=entry.record; C=entry.checkpoint;
    assert(strcmp(r.status,'ok') && isfinite(r.NPV_best), ...
        'p44:IncompleteRecord','B0 contains an unsuccessful/nonfinite grid.');
    assert(C.search_complete && C.candidate_coverage_complete, ...
        'p44:IncompleteSearch','A B0 candidate search is incomplete.');
    seen(end+1,1)=double(r.grid_index); %#ok<AGROW>
    assert(strcmp(C.model_signature,meta.model_signature), ...
        'p44:MixedBaseline','B0 checkpoint signatures differ.');
    if r.NPV_best<=0, continue; end
    assert(all(isfield(r,fields)) && isfield(r,'selected_candidate'), ...
        'p44:RecordSchema','B0 record lacks required geometry, cost or selected-candidate fields.');
    n=double(r.turbine_count); assert(n>=1 && n==round(n));
    assert(isequal(size(r.turbine_xy_m),[n,2]) && all(isfinite(r.turbine_xy_m),'all'));
    assert(abs(r.wind_farm_capacity-12*n)<1e-8,'p44:TurbineRating','P44 uses 12-MW turbines.');
    selected=r.selected_candidate;
    validateSelected(r,selected,price_CNY_per_MWh);
    checkpoint=struct('grid_index',r.grid_index,'search_complete',true, ...
        'candidate_coverage_complete',true,'model_signature',meta.model_signature, ...
        'selected_candidate',selected); %#ok<NASGU>
    save(fullfile(checkpointDir,sprintf('grid_%04d.mat',r.grid_index)), ...
        'checkpoint','-v7.3');
    assert(isstruct(r.platform_detail) && all(isfield(r.platform_detail, ...
        {'selected_components','selected_platform','selected_index'})), ...
        'p44:PlatformDetailSchema', ...
        'Stage1 platform details with selected cost components are required for grid %d.',r.grid_index);
    q=struct(); for f=fields, q.(f{1})=r.(f{1}); end
    q.platform_detail=struct('selected_components',r.platform_detail.selected_components, ...
        'selected_platform',r.platform_detail.selected_platform, ...
        'selected_index',r.platform_detail.selected_index);
    g=numel(records)+1; records{g,1}=q; ids(g,1)=r.grid_index; %#ok<AGROW>
    summaryRows(end+1,:)=[r.grid_index,r.wind_farm_capacity,r.NPV_best,r.turbine_count]; %#ok<AGROW>
end
assert(numel(unique(seen))==numel(seen),'p44:DuplicateGrid','Duplicate B0 grid IDs.');
assert(numel(seen)==meta.completed_grid_count && meta.completed_grid_count==meta.expected_grid_count, ...
    'p44:MissingGrid','Per-grid checkpoints do not cover the complete B0.');
assert(~isempty(records),'p44:EmptyPositivePool','No positive-NPV B0 grid is available.');
% Preserve B0 grid-ID order, which is also the original preparation order.
[ids,order]=sort(ids); records=records(order);
counts=cellfun(@(r)double(r.turbine_count),records);
xyCells=cellfun(@(r)double(r.turbine_xy_m),records,'UniformOutput',false);
coordinates=vertcat(xyCells{:});
owner=repelem((1:numel(records)).',counts); point_start=[1;1+cumsum(counts)];
conflict_pairs=p44_cross_grid_pairs(coordinates,owner,1694-1e-6);
grid_ids=ids; point_xy_m=coordinates; point_owner=owner;
schema='P44_B0_INPUT_V1'; baseline_dir=snapshotDir; baseline_file=publicCfg.baselineFile;
sourceInfo=dir(baseline_file); baseline_bytes=sourceInfo.bytes; model_signature=meta.model_signature;
baseline_mtime_datenum=sourceInfo.datenum; %#ok<NASGU>
save(priceFile,'price_CNY_per_MWh','-v7');
save(inputFile,'records','grid_ids','point_xy_m','point_owner','point_start', ...
    'conflict_pairs','schema','baseline_dir','baseline_file','baseline_bytes', ...
    'baseline_mtime_datenum','model_signature','-v7.3');
summary=array2table(sortrows(summaryRows,1),'VariableNames', ...
    {'grid_index','wind_farm_capacity_MW','NPV_best_CNY','turbine_count'});
summaryFile=fullfile(snapshotDir,'baseline_results_summary.csv');
writetable(summary,summaryFile,'Encoding','UTF-8');
baselineMeta=struct('model_signature',model_signature,'source_baseline_file',baseline_file, ...
    'source_baseline_sha256',baselineSHA);
writeJSON(fullfile(snapshotDir,'baseline_metadata.json'),baselineMeta);
writeJSON(fullfile(snapshotDir,'merge_status.json'),struct('num_pending',0, ...
    'all_stage4_complete',true,'all_candidate_tables_complete',true));
manifest=struct('schema',schema,'model_signature',model_signature, ...
    'baseline_file',baseline_file,'source_baseline_sha256',baselineSHA, ...
    'baseline_bytes',baseline_bytes,'candidates',numel(records), ...
    'original_positive_capacity_GW',sum(summary.wind_farm_capacity_MW)/1000, ...
    'turbines',size(coordinates,1),'cross_grid_conflict_pairs',size(conflict_pairs,1), ...
    'spacing_m',1694,'source_summary_sha256',p44_sha256(summaryFile,true), ...
    'frozen_price_source',priceFile,'frozen_price_source_sha256',p44_sha256(priceFile,true), ...
    'input_file_sha256',p44_sha256(inputFile,true),'preparation_fingerprint',fingerprint);
writeJSON(manifestFile,manifest);
end
function validateSelected(r,s,price)
needed={'epsilon_MW','storage_energy_MWh','export_mode','transmission_detail', ...
    'farm_delivery_MW','onshore_power_kW','storage_detail','annual_delivered_energy_kWh', ...
    'annual_revenue_CNY','pv_revenue_CNY','export_system_cost_CNY','battery_cost_CNY'};
assert(all(isfield(s,needed)),'p44:SelectedSchema','Incomplete selected B0 candidate.');
sd=s.storage_detail;
assert(all(isfield(sd,{'charge_MW','discharge_MW','curtailment_MW','energy_MWh','is_optimal'})) ...
    && sd.is_optimal,'p44:SelectedDispatch','Selected B0 dispatch is not verified optimal.');
assert(numel(s.farm_delivery_MW)==8760 && numel(s.onshore_power_kW)==8760 ...
    && numel(sd.energy_MWh)==8761,'p44:HourlySchema','Expected 8760-hour dispatch and 8761 SOC boundaries.');
assert(abs(sum(double(s.onshore_power_kW(:))/1000.*price)-s.annual_revenue_CNY) ...
    <=max(1,1e-10*abs(s.annual_revenue_CNY)),'p44:PriceConsistency','B0 price/revenue mismatch.');
factor=sum(.9928.^(0:24)./1.03.^(1:25));
assert(abs(s.annual_revenue_CNY*factor-s.pv_revenue_CNY)<=max(1,1e-10*abs(s.pv_revenue_CNY)), ...
    'p44:FinancialConvention','B0 differs from the frozen 25-year/3%%/0.72%% P44 convention.');
assert(abs(r.NPV_best-(s.pv_revenue_CNY-r.total_cost_best))<=max(1,1e-10*abs(r.NPV_best)), ...
    'p44:BaselineFinance','B0 lifecycle-cost identity failed.');
end
function writeJSON(file,value)
fid=fopen(file,'w','n','UTF-8'); assert(fid>0); closeFile=onCleanup(@()fclose(fid)); %#ok<NASGU>
fwrite(fid,unicode2native(jsonencode(value,'PrettyPrint',true),'UTF-8'),'uint8');
end
