function report=p44_export_results(D,state,cfg,folder,science)
% Statistics are explicitly unavailable for geometry-only unsuccessful runs.
ids=find(state.retained); rows=state.rows(ids);
assert(all(~cellfun(@isempty,rows)),'Selected result rows are missing.');
numeric={'grid_id','original_capacity_MW','capacity_MW','original_turbine_count', ...
    'turbine_count','deleted_turbine_count','original_NPV_CNY','NPV_CNY', ...
    'LCOE_CNY_per_kWh','AEP_wake_adjusted_MWh','annual_onshore_delivery_MWh', ...
    'farm_cost_CNY','collection_cost_CNY','total_cost_CNY','junction_count', ...
    'junction_proxy_cost_CNY','recompute_seconds'};
T=table();
for k=1:numel(numeric)
    T.(numeric{k})=cellfun(@(q)double(q.(numeric{k})),rows);
end
T.baseline_reused=cellfun(@(q)logical(q.baseline_reused),rows);
T.financial_evaluated=cellfun(@(q)logical(q.financial_evaluated),rows);
T.cache_file=string(cellfun(@(q)q.cache_file,rows,'UniformOutput',false));
writetable(T,fullfile(folder,'selected_grids.csv'),'Encoding','UTF-8');
keptGrid=[]; keptID=[]; keptXY=zeros(0,2);
deletedGrid=[]; deletedID=[]; deletedXY=zeros(0,2); deletedExcluded=false(0,1);
attempted=[];
for h=1:numel(state.repair_history)
    attempted=union(attempted,state.repair_history{h}.processed_grid_indices);
end
for g=attempted(:).'
    r=D.records{g}; pts=double(D.point_start(g)):double(D.point_start(g+1))-1;
    keep=state.keepGlobal(pts); xy=double(r.turbine_xy_m);
    if state.retained(g)
        keptGrid=[keptGrid;repmat(r.grid_index,sum(keep),1)]; %#ok<AGROW>
        keptID=[keptID;find(keep)]; keptXY=[keptXY;xy(keep,:)]; %#ok<AGROW>
    end
    deletedGrid=[deletedGrid;repmat(r.grid_index,sum(~keep),1)]; %#ok<AGROW>
    deletedID=[deletedID;find(~keep)]; deletedXY=[deletedXY;xy(~keep,:)]; %#ok<AGROW>
    deletedExcluded=[deletedExcluded;repmat(state.excluded(g),sum(~keep),1)]; %#ok<AGROW>
end
windTurbines=table(keptGrid,keptID,keptXY(:,1),keptXY(:,2), ...
    'VariableNames',{'grid_id','original_turbine_index','utm50_x_m','utm50_y_m'});
writetable(windTurbines,fullfile(folder,'selected_turbines.csv'),'Encoding','UTF-8');
deletedTurbines=table(deletedGrid,deletedID,deletedXY(:,1),deletedXY(:,2),deletedExcluded, ...
    'VariableNames',{'grid_id','original_turbine_index','utm50_x_m','utm50_y_m','entire_grid_excluded'});
writetable(deletedTurbines,fullfile(folder,'deleted_turbines.csv'),'Encoding','UTF-8');
pairs=double(D.conflict_pairs);
violations=sum(state.keepGlobal(pairs(:,1))&state.keepGlobal(pairs(:,2)));
assert(violations==0,'Final layout contains cross-grid spacing conflicts.');
actual=sum(T.capacity_MW);
financialComplete=~isempty(ids)&&all(T.financial_evaluated);
if financialComplete
    npv=sum(T.NPV_CNY); aep=sum(T.AEP_wake_adjusted_MWh);
    onshore=sum(T.annual_onshore_delivery_MWh);
else
    npv=NaN; aep=NaN; onshore=NaN;
end
report=struct('schema','P44_REPORT_V1','status',state.status, ...
    'target_capacity_GW',state.target_MW/1000,'capacity_tolerance_GW',cfg.CapacityToleranceMW/1000, ...
    'actual_capacity_GW',actual/1000,'capacity_shortfall_GW',max(0,state.target_MW-actual)/1000, ...
    'capacity_band_satisfied',actual>=state.target_MW-1e-6&&actual<=state.target_MW+cfg.CapacityToleranceMW+1e-6, ...
    'selected_grid_count',numel(ids),'selected_turbine_count',height(windTurbines), ...
    'initial_selected_grid_count',numel(state.initial_selected_ids), ...
    'initial_selected_capacity_GW',state.initial_selected_capacity_MW/1000, ...
    'initial_selection_NPV_CNY',state.initial_selection_NPV_CNY, ...
    'supplementary_grid_count',sum(~ismember(D.grid_ids(ids),state.initial_selected_ids)), ...
    'deleted_turbines_in_retained_grids',sum(T.deleted_turbine_count), ...
    'deleted_turbines_including_zero_grid_exclusions',height(deletedTurbines), ...
    'zero_capacity_excluded_grid_ids',D.grid_ids(state.excluded), ...
    'required_cross_grid_spacing_m',cfg.MinimumSpacingM, ...
    'cross_grid_spacing_numerical_tolerance_m',cfg.SpacingNumericalToleranceM, ...
    'cross_grid_spacing_conflict_pairs',violations, ...
    'minimum_cross_grid_spacing_certified_lower_bound_m',cfg.MinimumSpacingM-cfg.SpacingNumericalToleranceM, ...
    'spacing_check_basis','all cross-grid pairs within threshold precomputed on original coordinates; corrected points are a subset', ...
    'financial_evaluation_complete',financialComplete,'corrected_portfolio_NPV_CNY',npv, ...
    'corrected_wake_AEP_TWh_per_year',aep/1e6,'annual_onshore_delivery_TWh',onshore/1e6, ...
    'remaining_capacity_upper_bound_GW',state.remaining_capacity_upper_bound_MW/1000, ...
    'selection_rounds',state.iteration,'baseline_model_signature',cfg.BaselineModelSignature, ...
    'science_signature',cfg.ScienceSignature,'baseline_source',cfg.BaselineDir, ...
    'final_solution_is_heuristic',true,'dispatch_objective','original B0 farm-side hourly revenue LP; shore losses evaluated after dispatch', ...
    'junction_cost_basis','original support + mooring + full installation/O&M/decommissioning as conservative proxy', ...
    'wake_scope','within each original grid; cross-farm wakes are not recalculated', ...
    'routing_scope','original internal tree routes and OSS retained; independent export links and straight shore distance retained', ...
    'financial_missing_value_policy','NaN/null indicates unavailable corrected metrics, never substitute original NPV after turbine removal');
report.removed_capacity_in_retained_grids_GW=sum(T.original_capacity_MW-T.capacity_MW)/1000;
report.junction_count=sum(T.junction_count);
report.junction_proxy_cost_CNY=sum(T.junction_proxy_cost_CNY);
report.negative_corrected_NPV_retained_count=sum(T.NPV_CNY<=0 & T.financial_evaluated);
if ~isempty(state.selection_history)
    gaps=cellfun(@(v)v.mip_gap,state.selection_history);
    finiteGaps=gaps(isfinite(gaps));
    report.last_selection_MIP_gap=gaps(end);
    if isempty(finiteGaps); report.max_selection_MIP_gap=NaN;
    else; report.max_selection_MIP_gap=max(finiteGaps); end
    report.selection_solve_history=state.selection_history;
end
writeJSON(fullfile(folder,'portfolio_report.json'),report);
selection_history=state.selection_history; repair_history=state.repair_history;
selected_grid_ids=D.grid_ids(ids); selected_records=rows;
save(fullfile(folder,'portfolio_results.mat'),'report','selected_grid_ids','selected_records', ...
    'selection_history','repair_history','science','-v7.3');
end
function writeJSON(file,data)
fid=fopen(file,'w','n','UTF-8'); assert(fid>0); c=onCleanup(@()fclose(fid));
fwrite(fid,unicode2native(jsonencode(data,'PrettyPrint',true),'UTF-8'),'uint8');
end
