function out = p44_farm_cost(r,keepMask,junctionIndices,cfg)
%P44_FARM_COST Reprice fixed-platform subsets from original cost components.
% Development/licensing/survey costs are retained in full for a developed
% original grid. No platform type or 300-MW licensing threshold is reselected.
% Junctions conservatively retain original per-turbine support, mooring,
% installation, full O&M and decommissioning; turbine purchase is excluded.
% This is a support-facility proxy, not a separately calibrated junction cost.
if nargin<4; cfg=struct(); end %#ok<NASGU>
n=size(r.turbine_xy_m,1); keep=p44_keep_mask(keepMask,n);
junction=double(junctionIndices(:));
assert(all(isfinite(junction)) && all(junction==round(junction)) ...
    && all(junction>=1) && all(junction<=n) ...
    && numel(unique(junction))==numel(junction) ...
    && ~any(keep(junction)), ...
    'p44:JunctionIndices','Junctions must be distinct deleted original turbines.');
assert(isfield(r,'platform_detail') && isstruct(r.platform_detail) ...
    && isfield(r.platform_detail,'selected_components'), ...
    'p44:PlatformComponents','Original platform component costs are required.');
C=r.platform_detail.selected_components;
required={'development_licensing_CNY','turbine_procurement_CNY', ...
    'support_structure_CNY','mooring_system_CNY','installation_CNY', ...
    'PV_OM_CNY','PV_decommissioning_CNY'};
for j=1:numel(required)
    value=C.(required{j});
    assert(isnumeric(value) && isscalar(value) && isfinite(value) && value>=0, ...
        'p44:PlatformComponents','Invalid original platform component %s.',required{j});
end
nKeep=sum(keep); nJ=numel(junction);
assert(nKeep>0 || nJ==0,'p44:EmptyFarmJunction', ...
    'An empty farm cannot require collection junctions.');
a=nKeep/n; b=nJ/n;
supportProxy=double(C.support_structure_CNY)+double(C.mooring_system_CNY) ...
    +double(C.installation_CNY)+double(C.PV_OM_CNY)+double(C.PV_decommissioning_CNY);
development=double(C.development_licensing_CNY)*(nKeep>0);
components=struct('development_licensing_CNY',development, ...
    'turbine_procurement_CNY',a*double(C.turbine_procurement_CNY), ...
    'support_structure_CNY',(a+b)*double(C.support_structure_CNY), ...
    'mooring_system_CNY',(a+b)*double(C.mooring_system_CNY), ...
    'installation_CNY',(a+b)*double(C.installation_CNY), ...
    'PV_OM_CNY',(a+b)*double(C.PV_OM_CNY), ...
    'PV_decommissioning_CNY',(a+b)*double(C.PV_decommissioning_CNY));
total=development+a*double(C.turbine_procurement_CNY)+(a+b)*supportProxy;
if all(keep) && isfield(r,'platform_turbine_cost')
    assert(abs(total-double(r.platform_turbine_cost)) ...
        <=max(1,1e-7*abs(double(r.platform_turbine_cost))), ...
        'p44:BaselinePlatformCost','Original components and saved platform cost disagree.');
    total=double(r.platform_turbine_cost);
end
out=struct('platform_turbine_cost_CNY',total, ...
    'farm_lifecycle_cost_CNY',total,'components',components, ...
    'active_turbine_count',nKeep,'junction_count',nJ, ...
    'junction_original_indices',junction, ...
    'junction_proxy_cost_CNY',b*supportProxy, ...
    'junction_proxy_unit_cost_CNY',supportProxy/n, ...
    'retained_development_cost_CNY',development, ...
    'development_policy','retain original development/licensing/survey cost in full', ...
    'junction_cost_policy',['original per-turbine support + mooring + full installation ', ...
    '+ full O&M PV + decommissioning PV; exclude turbine procurement; conservative proxy']);
if isfield(r,'optimal_platform'); out.platform_type=r.optimal_platform;
elseif isfield(C,'platform_type'); out.platform_type=C.platform_type; end
end
