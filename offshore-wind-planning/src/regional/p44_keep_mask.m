function keep = p44_keep_mask(mask,n)
%P44_KEEP_MASK Validate a subset mask in original turbine index order.
assert((islogical(mask)||isnumeric(mask)) && isvector(mask) ...
    && numel(mask)==n && all(isfinite(double(mask(:)))) ...
    && all(mask(:)==0|mask(:)==1), ...
    'p44:KeepMask','keepMask must have one binary entry per original turbine.');
keep=logical(mask(:));
end
